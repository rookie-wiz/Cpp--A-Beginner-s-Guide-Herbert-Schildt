// The following program uses the * operator to compute the area of a rectangle given its length and the width.
#include <iostream>
using namespace std;

/*
Logic : Area of Rectange is Length X Width 
- use * operator 
- three variables length and width , area
- Area = Return the Product value 
*/ 
int main(){
    int length , width , area;
    length = 10;
    width = 10;
    area = length * width;
    cout << "Area of Reactangle is " ;
    cout << area << endl;
    return 0;
}